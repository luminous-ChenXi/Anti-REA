// Poison: decoy/honeypot generator.
// Rationale: REA's conclusions must be "evidence-backed"; its string dumps and
// function names are the raw feed for the LLM. Mixing plausible-but-misleading
// decoys (fake endpoints, fake license formats, honeypot markers) into the
// artifact dilutes LLM attention toward fake assets — and honeypot markers act
// as tripwires (a decoy being touched = reverse engineering in progress).
// Note: generates harmless fake data only; never fabricates usable credentials
// under real third-party domains.

import { rng, seedFromString } from "../util.js";

const WORDS_A = ["license", "telemetry", "auth", "billing", "sync", "gateway", "metrics", "registry", "session", "provision", "entitle", "roaming"];
const WORDS_B = ["validator", "service", "endpoint", "channel", "bridge", "relay", "provider", "daemon", "portal", "hub"];
const DOMAINS = ["svc", "infra", "internal", "backend", "core", "node"];
const FEATURES = ["ProTrialReset", "CloudLicenseV2", "OfflineActivation", "EnterpriseSSOBridge", "FeatureFlagSync", "DeviceFingerprintV3", "SeatTransferLock", "GracePeriodKeygen"];

function pick(rand, arr) {
  return arr[Math.floor(rand() * arr.length)];
}

function fakeKey(rand, prefix) {
  const chars = "ABCDEF0123456789";
  let s = prefix;
  for (let i = 0; i < 32; i++) s += chars[Math.floor(rand() * chars.length)];
  return s;
}

export function generateDecoys({ count = 40, seed = "anti-rea" } = {}) {
  const rand = rng(seedFromString(seed));
  const decoys = [];
  for (let i = 0; i < count; i++) {
    const kind = Math.floor(rand() * 6);
    const a = pick(rand, WORDS_A), b = pick(rand, WORDS_B);
    if (kind === 0) {
      decoys.push({ kind: "endpoint", value: `https://api.${a}-${pick(rand, DOMAINS)}.net/v2/${a}/${Math.floor(rand() * 900 + 100)}`, note: "fake endpoint: domain does not exist, probing fails" });
    } else if (kind === 1) {
      decoys.push({ kind: "license-key", value: fakeKey(rand, "ARLIC-"), note: "fake license format: rejected server-side if ever used" });
    } else if (kind === 2) {
      decoys.push({ kind: "api-key", value: fakeKey(rand, "sk-antirea-"), note: "fake API key (non-issuable format, never a real prefix)" });
    } else if (kind === 3) {
      const f = pick(rand, FEATURES);
      decoys.push({ kind: "feature", value: f, note: "fake feature name: lures analysts into researching a capability that does not exist" });
    } else if (kind === 4) {
      decoys.push({ kind: "config", value: `${pick(rand, WORDS_A).toUpperCase()}_ENDPOINT=${`https://cfg.${pick(rand, DOMAINS)}.net/config/${Math.floor(rand() * 99)}`}`, note: "fake config entry" });
    } else {
      decoys.push({ kind: "honeypot", value: `__anti_rea_honeypot_${Math.floor(rand() * 100000)}__`, note: "honeypot marker: guard treats any read of this symbol as active reverse engineering" });
    }
  }
  return decoys;
}

/** Render decoys as includable source for each language. */
export function renderDecoys(decoys, format) {
  if (format === "json") return JSON.stringify(decoys, null, 2);
  if (format === "text") return decoys.map((d) => `${d.value}    # ${d.note}`).join("\n") + "\n";
  if (format === "js") {
    return `// Generated by anti-rea poison — decoy constant pool. Mix with real strings in the same array.\n` +
      `export const RESOURCES = [\n` +
      decoys.map((d) => `  "${d.value}",`).join("\n") +
      `\n];\n`;
  }
  if (format === "c") {
    return `/* Generated by anti-rea poison — decoy string table */\n` +
      `static const char *const kResources[] = {\n` +
      decoys.map((d) => `  "${d.value}",`).join("\n") +
      `\n};\n`;
  }
  if (format === "csharp") {
    return `// Generated by anti-rea poison — decoy resource table\n` +
      `internal static class DecoyResources {\n` +
      `  internal static readonly string[] All = {\n` +
      decoys.map((d) => `    "${d.value}",`).join("\n") +
      `\n  };\n` +
      `}\n`;
  }
  if (format === "python") {
    return `# Generated by anti-rea poison — decoy resources\nRESOURCES = [\n` + decoys.map((d) => `  "${d.value}",`).join("\n") + `\n]\n`;
  }
  throw new Error(`unknown format: ${format}`);
}
